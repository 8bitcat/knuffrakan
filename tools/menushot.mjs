// Nya menyn: SPELA / GÅ MED I RUM, kodskylten, lobbyn med RACE/GRAND PRIX och spelets låtar
import { createRequire } from 'module';
const require = createRequire('D:/Qisy/QISYFrontend/QISYFrontend-1/package.json');
const { chromium } = require('playwright');
const base = process.env.BASE || 'http://localhost:8810/';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=d3d11', '--autoplay-policy=no-user-gesture-required'] });
const errors = [];
const p = await (await browser.newContext({ viewport: { width: 1280, height: 860 } })).newPage();
p.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
await p.goto(base);
await p.waitForFunction(() => window.ready === true, null, { timeout: 90000 });
await p.waitForTimeout(600);
await p.screenshot({ path: 'tools/out/meny2.png' });
await p.click('#roomopen'); await p.keyboard.type('Henrik!'); await p.waitForTimeout(300);
await p.screenshot({ path: 'tools/out/meny2-kod.png' });
await p.keyboard.press('Enter');
await p.waitForFunction(() => window.__game?.me && window.__game.race.phase === 'lobby', null, { timeout: 60000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: 'tools/out/meny2-lobby.png' });
console.log('rum:', await p.evaluate(() => window.__game.room), '| musik:', await p.evaluate(() => { const m = window.__game.audio.music; return `${m.choice} «${m.fileName}» spelar ${m.playing} ${m.src?.el ? m.src.el.currentTime.toFixed(1) + ' s' : ''}`; }));
await p.waitForTimeout(2000);
console.log('musik efter 2 s:', await p.evaluate(() => { const m = window.__game.audio.music; return `${m.src?.el?.currentTime.toFixed(1)} s av ${m.src?.el?.duration.toFixed(0)} s`; }));
await p.evaluate(() => { const el = window.__game.audio.music.src?.el; if (el) el.currentTime = el.duration - 0.5; });
await p.waitForTimeout(2500);
console.log('nästa låt:', await p.evaluate(() => { const m = window.__game.audio.music; return `«${m.fileName}» ${m.src?.el?.currentTime.toFixed(1)} s`; }));
await p.click('#sb-mus'); await p.waitForTimeout(500);
await p.screenshot({ path: 'tools/out/meny2-musik.png' });
console.log(errors.length ? errors.join('\n') : 'inga fel');
await browser.close();
